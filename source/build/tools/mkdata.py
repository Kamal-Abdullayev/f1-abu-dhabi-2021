"""Inline the four input packs as JavaScript constants: TRACK, RACE, EXTRA, CITY.
Usage: python3 -I mkdata.py <out_dir with the .json packs> <data.js to write>
This may be extended (trim CITY far from the circuit, add a water mask) but the four names must stay."""
import json
import os
import sys

outd, dst = sys.argv[1], sys.argv[2]


def load(n):
    with open(os.path.join(outd, n), encoding='utf-8') as f:
        return json.load(f)


parts = [('TRACK', 'track_pack.json'), ('RACE', 'race_pack.json'), ('EXTRA', 'race_extra.json'), ('CITY', 'city_pack.json')]
with open(dst, 'w', encoding='utf-8') as f:
    f.write('/* data.js : generated by tools/mkdata.py, do not edit by hand.\n'
            '   Timing data: Jolpica F1 API (Ergast-compatible), CC BY-NC-SA 4.0. Map data (c) OpenStreetMap contributors, ODbL. */\n')
    for name, fn in parts:
        s = json.dumps(load(fn), separators=(',', ':'), ensure_ascii=True).replace('</', '<\\/')
        f.write('const %s=%s;\n' % (name, s))
print('wrote', dst, os.path.getsize(dst), 'bytes')
